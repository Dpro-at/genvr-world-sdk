export function halton(index: number, base: number): number {
  let f = 1,
    result = 0;
  while (index > 0) {
    f /= base;
    result += f * (index % base);
    index = Math.floor(index / base);
  }
  return result;
}
export const lanczos2Sq = (x: number): number => {
  const q = Math.min(x, 4),
    a = 0.4 * q - 1,
    b = 0.25 * q - 1;
  return (1.5625 * a * a - 0.5625) * b * b;
};
