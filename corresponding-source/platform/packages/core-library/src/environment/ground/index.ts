/**
 * The ground each kind of starter world starts with (P2-40 task 7, design 3.4), by soil. Each
 * material is of the soil whose slot it takes, because the slot, not the look, is what placement
 * rules read (a tree wants grass or dirt). Soils left out keep `DEFAULT_GROUND`.
 */
export const STARTER_GROUND: Record<WorldSeed['kind'], Partial<Record<SoilName, string>>> = {
  valley: { grass: 'grass-001' },
  island: { grass: 'grass-005' },
  plain: {},
  mountains: { grass: 'grass-008', rock: 'rock-063', dirt: 'ground-110' },
};

/** A kind of world's ground as the place's palette slots (`terrain.materials`). */
export function starterGroundMaterials(kind: WorldSeed['kind']): Record<string, GroundMaterialRef> {
  const slots: Record<string, GroundMaterialRef> = {};
  for (const [soil, name] of Object.entries(STARTER_GROUND[kind]) as Array<[SoilName, string]>) {
    const material = getGround(name);
    if (!material || material.soil !== soil) throw new Error(`${name} is not a ${soil} ground material`);
    slots[String(SoilName.options.indexOf(soil))] = groundRef(material);
  }
  return slots;
}

/** The ground material with this id or file name. */
export const getGround = (idOrName: string): GroundMaterial | undefined =>
  GROUND_MATERIALS.find((material) => material.manifest.id === idOrName || material.name === idOrName);
