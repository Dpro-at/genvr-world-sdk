/**
 * Items not opened to every place yet (decision 130): found by `getCoreItem`, left out of `CORE_ITEMS`, the
 * catalogs and the library.
 */
export const EXPERIMENTAL_ITEMS: readonly CoreItem[] = [...TIDEWATER_ITEMS];

const byId = new Map([...CORE_ITEMS, ...EXPERIMENTAL_ITEMS].map((item) => [item.manifest.id, item]));

/** Names of the generator parameters of an item with a generated look (decision 130), sorted; empty otherwise. */
export function generatedParamKeys(id: string): string[] {
  const item = byId.get(id);
  const look = item ? anyGeneratedLook(item) : null;
  return look ? Object.keys(look.generated.params).sort() : [];
}

export const getCoreItem = (id: string): CoreItem | undefined => byId.get(id);
